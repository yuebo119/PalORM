    private static void GenerateBindDeleteBody(TableModel model, StringBuilder sb)
    {
        var pkCols = model.Columns.AsSpan().ToArray().Where(c => c.IsPrimaryKey).ToArray();
        int pi = 0;
        foreach (var col in pkCols)
        {
            string castExpr = col.ConverterTypeName is not null
                ? $"({col.ClrTypeName})key"
                : NormalizeClrType(col.ClrTypeName) switch
            {
                // 整数主键用 Convert.ToXxx(key) 而非直接 cast：
                // 调用方可能传 int（如 BenchmarkDotNet 的 NextId()）、byte 等装箱为 object，
                // 直接 (long)key 在 key 是 int 时抛 InvalidCastException（ITM-587）。
                // Convert 在装箱类型间自动转换，代价仅几 ns，GetByKey 21μs 路径可忽略。
                "long" or "global::System.Int64" => "global::System.Convert.ToInt64(key)",
                "int" or "global::System.Int32" => "global::System.Convert.ToInt32(key)",
                "short" or "global::System.Int16" => "global::System.Convert.ToInt16(key)",
                "byte" or "global::System.Byte" => "global::System.Convert.ToByte(key)",
                // string/Guid 保持精确 cast——语义不同（不接受 int→string 隐式转换）
                "string" or "global::System.String" => "((string)key)",
                "global::System.Guid" => "((global::System.Guid)key)",
                _ => "key"
            };
            string providerValueExpr = col.ConverterTypeName is null
                ? castExpr
                : $"_conv_{col.PropertyName}.ToProvider({castExpr})";
            string valueExpr = col.IsNullable
                ? $"{castExpr} is null ? global::System.DBNull.Value : (object){providerValueExpr}"
                : $"(object){providerValueExpr}";
            sb.AppendLine($"        {{ var p = cmd.CreateParameter(); p.ParameterName = \"@p{pi}\"; p.Value = {valueExpr}; cmd.Parameters.Add(p); }}");
            pi++;
        }
    }

    private static void GenerateHasDefaultKeyBody(TableModel model, StringBuilder sb)
    {
        var pkColumn = model.Columns.AsSpan().ToArray().FirstOrDefault(c => c.IsPrimaryKey);
        if (pkColumn is null)
        {
            sb.AppendLine("        return true;");
            return;
        }
        sb.AppendLine($"        return global::System.Collections.Generic.EqualityComparer<{pkColumn.ClrTypeName}>.Default.Equals(entity.{pkColumn.PropertyName}, default);");
    }

    private static void GenerateIncrementVersionBody(TableModel model, StringBuilder sb)
    {
        var concurrencyColumn = model.Columns.AsSpan().ToArray().FirstOrDefault(c => c.IsConcurrencyToken);
        if (concurrencyColumn is null) return;
        sb.AppendLine($"        entity.{concurrencyColumn.PropertyName}++;");
    }

    private static void GenerateSetIdBody(TableModel model, StringBuilder sb)
    {
        var pkCol = model.Columns.AsSpan().ToArray().FirstOrDefault(c => c.IsPrimaryKey);
        if (pkCol is null || !pkCol.IsAutoIncrement)
        {
            sb.AppendLine("        // 仅自增 int/long 主键需要数据库 ID 回填");
            return;
        }
        // 生成的代码: entity.Id = id; 或 entity.UserId = (int)id;（IsAutoIncrement 已限定 int/long）
        string cast = NormalizeClrType(pkCol.ClrTypeName) switch
        {
            "int" or "global::System.Int32" => "(int)",
            "long" or "global::System.Int64" => "",
            _ => "(long)" // 默认转为 long 再写入
        };
        sb.AppendLine($"        entity.{pkCol.PropertyName} = {cast}id;");
    }

    /// <summary>去除可空标注（string? → string），供主键类型精确匹配——EndsWith 匹配
    /// 会误伤 uint/ulong（ITM-505）。主键不会是可空引用类型，此处仅剥可能的尾随 '?'。</summary>
    private static string NormalizeClrType(string clrTypeName)
        => clrTypeName.EndsWith("?", System.StringComparison.Ordinal)
            ? clrTypeName.Substring(0, clrTypeName.Length - 1)
            : clrTypeName;

    internal static string BuildInsertSql(TableModel model)
        => BuildInsertSql(model, null);

    internal static string BuildInsertSql(TableModel model, SqlGenerationDialect? dialect)
    {
        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);
        ColumnModel[] columns = model.Columns.AsSpan().ToArray()
            .Where(static column => column.IsInsertable).ToArray();
        var parameterNames = columns.Select((_, index) => $"@p{index}");
        return $"INSERT INTO {Quote(model.TableName)} " +
            $"({string.Join(", ", columns.Select(column => Quote(column.ColumnName)))}) " +
            $"VALUES ({string.Join(", ", parameterNames)})";
    }

    // ITM-552：UPDATE 的 SET 列谓词——BuildUpdateSql（生成 SQL）与 GenerateBindUpdateBody（绑定参数）
    // 曾各自内联复制此条件，二者必须逐字一致否则参数序与占位符错位。提取为单一真源防漂移。
    private static bool IsUpdatableColumn(ColumnModel col)
        => !col.IsPrimaryKey && !col.IsConcurrencyToken
            && !col.IsTimestamp && col.ComputedExpression is null;

    internal static string BuildUpdateSql(TableModel model)
        => BuildUpdateSql(model, null);

    internal static string BuildUpdateSql(TableModel model, SqlGenerationDialect? dialect)
    {
        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);
        ColumnModel[] columns = model.Columns.AsSpan().ToArray();
        ColumnModel[] primaryKeys = columns.Where(static column => column.IsPrimaryKey).ToArray();
        ColumnModel[] setColumns = columns.Where(static column =>
            IsUpdatableColumn(column)).ToArray();
        ColumnModel? concurrency = columns.FirstOrDefault(static column => column.IsConcurrencyToken);
        int parameterIndex = 0;
        var sets = setColumns.Select(column =>
            $"{Quote(column.ColumnName)} = @p{parameterIndex++}").ToList();
        if (concurrency is not null)
            sets.Add($"{Quote(concurrency.ColumnName)} = {Quote(concurrency.ColumnName)} + 1");
        if (sets.Count == 0)
            return string.Empty;

        var conditions = primaryKeys.Select(column =>
            $"{Quote(column.ColumnName)} = @p{parameterIndex++}").ToList();
        if (concurrency is not null)
            conditions.Add($"{Quote(concurrency.ColumnName)} = @p{parameterIndex}");
        return $"UPDATE {Quote(model.TableName)} SET {string.Join(", ", sets)} " +
            $"WHERE {string.Join(" AND ", conditions)}";
    }

    internal static string BuildDeleteSql(TableModel model)
        => BuildDeleteSql(model, null);

    internal static string BuildDeleteSql(TableModel model, SqlGenerationDialect? dialect)
    {
        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);
        ColumnModel[] primaryKeys = model.Columns.AsSpan().ToArray()
            .Where(static column => column.IsPrimaryKey).ToArray();
        var conditions = primaryKeys.Select((column, index) =>
            $"{Quote(column.ColumnName)} = @p{index}");
        return $"DELETE FROM {Quote(model.TableName)} WHERE " +
            string.Join(" AND ", conditions);
    }

    internal static string BuildInsertReturningSql(TableModel model)
        => BuildInsertReturningSql(model, null);

    internal static string BuildInsertReturningSql(
        TableModel model, SqlGenerationDialect? dialect)
    {
        // MySQL 无 RETURNING：生成空串而非无效 SQL——绕过 SupportsReturningClause 守卫的
        // 误用会以"空 CommandText"明确失败，不会把非法语句发给服务器。
        if (dialect == SqlGenerationDialect.MySql)
            return string.Empty;
        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);
        return BuildInsertSql(model, dialect) + " RETURNING " +
            string.Join(", ", model.Columns.AsSpan().ToArray()
                .Select(column => Quote(column.ColumnName)));
    }

    // ── Upsert SQL 预构建（v4.1 性能优化：消除运行时 LINQ + string.Join 拼接）──
    // 运行时 UpsertWithReturningAsync / UpsertWithMySqlAsync 直接取 const，零分配。

    internal static string BuildUpsertReturningSql(TableModel model)
        => BuildUpsertReturningSql(model, null);

    internal static string BuildUpsertReturningSql(
        TableModel model, SqlGenerationDialect? dialect)
    {
        // MySQL 无 RETURNING：空串
        if (dialect == SqlGenerationDialect.MySql)
            return string.Empty;

        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);

        ColumnModel[] upsertColumns = model.Columns.AsSpan().ToArray()
            .Where(static column => column.IsUpsertable).ToArray();
        ColumnModel[] pkCols = upsertColumns.Where(static c => c.IsPrimaryKey).ToArray();
        if (pkCols.Length == 0)
            return string.Empty;

        string pkColumnName = pkCols[0].ColumnName;
        string[] updateColumns = upsertColumns
            .Where(column => !string.Equals(column.ColumnName, pkColumnName, StringComparison.Ordinal))
            .Select(column => Quote(column.ColumnName))
            .ToArray();

        string conflictAction = updateColumns.Length == 0
            ? "DO NOTHING"
            : "DO UPDATE SET " + string.Join(", ", updateColumns.Select(column =>
                $"{column} = excluded.{column}"));

        string columnList = string.Join(", ", upsertColumns.Select(c => Quote(c.ColumnName)));
        string valueList = string.Join(", ",
            Enumerable.Range(0, upsertColumns.Length).Select(static index => $"@p{index}"));
        string returningList = string.Join(", ", model.Columns.AsSpan().ToArray()
            .Select(column => Quote(column.ColumnName)));

        return $"INSERT INTO {Quote(model.TableName)} ({columnList}) " +
            $"VALUES ({valueList}) ON CONFLICT " +
            $"({Quote(pkColumnName)}) {conflictAction} " +
            $"RETURNING {returningList}";
    }

    internal static string BuildUpsertMySqlSql(TableModel model)
        => BuildUpsertMySqlSql(model, null);

    internal static string BuildUpsertMySqlSql(
        TableModel model, SqlGenerationDialect? dialect)
    {
        string Quote(string value) => dialect is null
            ? value
            : SqlGeneration.QuoteIdentifier(value, dialect.Value);

        ColumnModel[] upsertColumns = model.Columns.AsSpan().ToArray()
            .Where(static column => column.IsUpsertable).ToArray();
        ColumnModel[] pkCols = upsertColumns.Where(static c => c.IsPrimaryKey).ToArray();
        if (pkCols.Length == 0)
            return string.Empty;

        string pkColumnName = pkCols[0].ColumnName;
        string[] updateColumns = upsertColumns
            .Where(column => !string.Equals(column.ColumnName, pkColumnName, StringComparison.Ordinal))
            .Select(column => Quote(column.ColumnName))
            .ToArray();

        string columnList = string.Join(", ", upsertColumns.Select(c => Quote(c.ColumnName)));
        string valueList = string.Join(", ",
            Enumerable.Range(0, upsertColumns.Length).Select(static index => $"@p{index}"));

        // ON DUPLICATE KEY UPDATE：非 PK 列更新，自增 PK 用 LAST_INSERT_ID(id) 回填
        var assignments = updateColumns.Select(col =>
            col == Quote(pkCols[0].ColumnName) && pkCols[0].IsAutoIncrement
                ? $"{Quote(pkColumnName)} = LAST_INSERT_ID({Quote(pkColumnName)})"
                : $"{col} = VALUES({col})").ToArray();

        string conflictAction = assignments.Length == 0
            ? ""
            : " ON DUPLICATE KEY UPDATE " + string.Join(", ", assignments);

        return $"INSERT INTO {Quote(model.TableName)} ({columnList}) VALUES ({valueList}){conflictAction}";
    }

    private static void GenerateBindInsertBody(TableModel model, StringBuilder sb)
        => GenerateBindBody(model, sb, static column => column.IsInsertable, withOffset: true);

    private static void GenerateBindUpsertBody(TableModel model, StringBuilder sb)
        => GenerateBindBody(model, sb, static column => column.IsUpsertable, withOffset: false);

    /// <summary>共享 Bind 循环。v4.1：withOffset=true 时参数名用 @p{paramOffset+pi}（批量直绑），false 时用 @p{pi}（单行）。</summary>
    private static void GenerateBindBody(TableModel model, StringBuilder sb, Func<ColumnModel, bool> predicate, bool withOffset)
    {
        int pi = 0;
        foreach (var col in model.Columns.AsSpan())
        {
            if (!predicate(col)) continue;
            string valueExpr = GetParameterValueExpression(col);
            // withOffset=true 时生成 $\"@p{paramOffset + N}\"（插值表达式），false 时生成 \"@pN\"（字面量）
            string paramName = withOffset ? $"global::PalORM.ParameterNameCache.GetName(paramOffset + {pi})" : $"\"@p{pi}\"";
            sb.AppendLine($"        {{ var p = cmd.CreateParameter(); p.ParameterName = {paramName}; p.Value = {valueExpr}; cmd.Parameters.Add(p); }}");
            pi++;
        }
    }

    /// <summary>v4.6：仅设置预分配参数的 Value（无 CreateParameter/Add/ParameterName），用于跨批参数复用。</summary>
    private static void GenerateBindValuesBody(TableModel model, StringBuilder sb)
    {
        int pi = 0;
        foreach (var col in model.Columns.AsSpan())
        {
            if (!col.IsInsertable) continue;
            string valueExpr = GetParameterValueExpression(col);
            sb.AppendLine($"        parameters[paramOffset + {pi}].Value = {valueExpr};");
            pi++;
        }
    }

    // v4.1：MySQL INSERT + SELECT LAST_INSERT_ID() 预构建，消除运行时 string 拼接
    internal static string BuildInsertWithLastInsertIdSql(TableModel model)
        => BuildInsertWithLastInsertIdSql(model, null);

    internal static string BuildInsertWithLastInsertIdSql(
        TableModel model, SqlGenerationDialect? dialect)
        => BuildInsertSql(model, dialect) + "; SELECT LAST_INSERT_ID()";

    private static void GenerateBindUpdateBody(TableModel model, StringBuilder sb)
    {
        var cols = model.Columns.AsSpan().ToArray();
        var setCols = cols.Where(c => IsUpdatableColumn(c)).ToArray();
        var pkCols = cols.Where(c => c.IsPrimaryKey).ToArray();
        var cc = cols.FirstOrDefault(c => c.IsConcurrencyToken);

        int pi = 0;
        foreach (var col in setCols)
        {
            string valueExpr = GetParameterValueExpression(col);
            sb.AppendLine($"        {{ var p = cmd.CreateParameter(); p.ParameterName = \"@p{pi++}\"; p.Value = {valueExpr}; cmd.Parameters.Add(p); }}");
        }
        foreach (var col in pkCols)
        {
            string valueExpr = GetParameterValueExpression(col);
            sb.AppendLine($"        {{ var p = cmd.CreateParameter(); p.ParameterName = \"@p{pi++}\"; p.Value = {valueExpr}; cmd.Parameters.Add(p); }}");
        }
        if (cc is not null)
        {
            sb.AppendLine($"        {{ var p = cmd.CreateParameter(); p.ParameterName = \"@p{pi}\"; p.Value = entity.{cc.PropertyName}; cmd.Parameters.Add(p); }}");
        }
    }

    private static string GetParameterValueExpression(ColumnModel col)
    {
        if (IsObjectOwnedJson(col))
            return col.IsNullable
                ? $"entity.{col.PropertyName} is null ? global::System.DBNull.Value : (object)global::System.Text.Json.JsonSerializer.Serialize(entity.{col.PropertyName}, JsonTypeInfo_{col.PropertyName})"
                : $"(object)global::System.Text.Json.JsonSerializer.Serialize(entity.{col.PropertyName}, JsonTypeInfo_{col.PropertyName})";

        string valueExpression = col.ConverterTypeName is null
            ? $"entity.{col.PropertyName}"
            : $"_conv_{col.PropertyName}.ToProvider(entity.{col.PropertyName})";
        return col.IsNullable
            ? $"entity.{col.PropertyName} is null ? global::System.DBNull.Value : (object){valueExpression}"
            : $"(object){valueExpression}";
    }

    private static bool IsObjectOwnedJson(ColumnModel column)
        => column.IsOwnedJson
            && column.ClrTypeName is not "string" and not "global::System.String";
}
