    /// 会抛 InvalidCastException）；SQL NULL 由 <c>default</c>（值类型的 <c>T?</c> 之 null）
    /// 或 <c>null</c>（引用类型）表达。可空值类型列声明为 <c>T?[]</c>，探针 Q4 实测 PG 正确写 NULL。</para>
