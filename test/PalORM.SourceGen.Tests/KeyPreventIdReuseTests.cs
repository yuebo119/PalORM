using System.Collections.Immutable;
using Microsoft.CodeAnalysis;

namespace PalORM.SourceGen.Tests;

/// <summary>P1-2（2026-11-26）：SQLite 自增主键的 <c>AUTOINCREMENT</c> 改为 opt-in。
/// <para>默认生成 <c>INTEGER PRIMARY KEY</c>：官方文档称 <c>AUTOINCREMENT</c> 有额外的
/// CPU / 内存 / 磁盘开销，本仓实测 20 万行顺序插入慢 43%。代价是物理删除最大 ROWID 的行后
/// 新值可能复用且不再严格升序，需要该语义的表显式标注 <c>[Key(PreventIdReuse = true)]</c>。</para>
/// <para>另锁 PALORM055：<c>PreventIdReuse</c> 与显式 <c>AutoIncrement = false</c> 并存是
/// 静默无效组合（应用侧赋值的主键不经 ROWID 分配），编译期报错。</para></summary>
internal sealed class KeyPreventIdReuseTests
{
    private const string DefaultKeySource = """
        using PalORM;
        [Table("t")]
        public sealed class E
        {
            [Key] public long Id { get; set; }
            [Column("name")] public string Name { get; set; } = "";
        }
        """;

    private const string PreventReuseSource = """
        using PalORM;
        [Table("t")]
        public sealed class E
        {
            [Key(PreventIdReuse = true)] public long Id { get; set; }
            [Column("name")] public string Name { get; set; } = "";
        }
        """;

    [Test]
    public async Task DefaultAutoIncrementKey_SqliteDdlOmitsAutoincrement()
    {
        string migration = MigrationSourceFor(DefaultKeySource);

        await Assert.That(migration).DoesNotContain("AUTOINCREMENT");
        await Assert.That(migration).Contains("INTEGER PRIMARY KEY");
    }

    [Test]
    public async Task PreventIdReuse_SqliteDdlEmitsAutoincrement()
    {
        string migration = MigrationSourceFor(PreventReuseSource);

        await Assert.That(migration).Contains("PRIMARY KEY AUTOINCREMENT");
    }

    [Test]
    public async Task KeyFormsDifferOnlyByAutoincrementKeyword()
    {
        // 差分断言：把 opt-in 形态里的关键字还原后与默认形态逐字相同——证明差异只在这一个词，
        // PostgreSQL 的 GENERATED BY DEFAULT AS IDENTITY 与 MySQL 的 AUTO_INCREMENT 均未受影响。
        string withKeyword = MigrationSourceFor(PreventReuseSource);
        string withoutKeyword = MigrationSourceFor(DefaultKeySource);

        await Assert.That(withKeyword.Replace("PRIMARY KEY AUTOINCREMENT", "PRIMARY KEY", StringComparison.Ordinal))
            .IsEqualTo(withoutKeyword);
    }

    [Test]
    public async Task PALORM055_PreventIdReuseWithAutoIncrementFalse_Reports()
    {
        const string source = """
            using PalORM;
            [Table("t")]
            public sealed class E
            {
                [Key(AutoIncrement = false, PreventIdReuse = true)] public long Id { get; set; }
                [Column("name")] public string Name { get; set; } = "";
            }
            """;

        (ImmutableArray<Diagnostic> diagnostics, _) = await AnalyzerDiagnosticsTests.AnalyzeAsync(source);

        await Assert.That(diagnostics.Any(static d => d.Id == "PALORM055")).IsTrue();
        await Assert.That(diagnostics.Single(static d => d.Id == "PALORM055").Severity)
            .IsEqualTo(DiagnosticSeverity.Error);
    }

    [Test]
    public async Task PALORM055_PreventIdReuseOnDefaultAutoIncrementKey_DoesNotReport()
    {
        (ImmutableArray<Diagnostic> diagnostics, _) = await AnalyzerDiagnosticsTests.AnalyzeAsync(PreventReuseSource);

        await Assert.That(diagnostics.Any(static d => d.Id == "PALORM055")).IsFalse();
    }

    /// <summary>取该实体生成的 Migration 源（单实体源只有一个 Migration 文件，含三方言 DDL）。</summary>
    private static string MigrationSourceFor(string source)
    {
        GeneratorTestHost.GeneratorResult result =
            GeneratorTestHost.RunGenerator(source, "PreventIdReuseConsumer");
        return result.GeneratedSources
            .Single(static pair => pair.Key.StartsWith("Migration_", StringComparison.Ordinal))
            .Value;
    }
}
